import { ChevronLeft, CircleHelp, KeyRound, Network, Unplug } from "lucide-react";
import Link from "next/link";

import { ShareButton } from "@/components/share-button";
import { SourceList } from "@/components/source-list";
import { panel, panelHeader, pill } from "@/components/ui";
import { formatGeneratedAt } from "@/lib/format";
import type { AppCard } from "@/types/guide";

export const CATEGORY_LABEL: Record<AppCard["category"], string> = {
  no_oauth: "No OAuth for third parties",
  platform: "Integration platform",
  unknown: "Couldn't confirm",
};

const CATEGORY_ICON = { no_oauth: Unplug, platform: Network, unknown: CircleHelp };

/** Why there's no setup guide, in one line. */
export function cardHeadline({ name, category }: AppCard): string {
  switch (category) {
    case "no_oauth":
      return `${name} doesn't offer OAuth to third-party apps`;
    case "platform":
      return `${name} is an integration platform, not an OAuth provider`;
    case "unknown":
      return `We couldn't confirm whether ${name} offers OAuth to third-party apps`;
  }
}

export function CategoryTag({ category }: { category: AppCard["category"] }) {
  const Icon = CATEGORY_ICON[category];
  return (
    <span className="inline-flex items-center gap-[5px] rounded-sm bg-hover px-1.5 py-px text-[12px] font-medium text-text-2">
      <Icon size={13} strokeWidth={1.8} aria-hidden="true" />
      {CATEGORY_LABEL[category]}
    </span>
  );
}

const label = "mb-1 font-mono text-[11px] tracking-[.08em] text-text-3 uppercase";

/** What the app is, the auth it uses and what to do instead. */
export function CardFacts({ card }: { card: AppCard }) {
  return (
    <dl className="flex flex-col gap-4 text-[14px] text-text-2">
      <div>
        <dt className={label}>What it is</dt>
        <dd className="[overflow-wrap:anywhere]">{card.summary}</dd>
      </div>
      <div>
        <dt className={label}>Auth it uses</dt>
        <dd>
          {card.authMethods.length > 0 ? (
            <ul className="flex flex-wrap gap-1.5">
              {card.authMethods.map((method) => (
                <li
                  key={method}
                  className="inline-flex items-center gap-1.5 rounded-sm border border-border bg-surface-2 px-2 py-0.5 text-[13px] text-text [overflow-wrap:anywhere]"
                >
                  <KeyRound size={12} strokeWidth={1.8} className="text-text-3" aria-hidden="true" />
                  {method}
                </li>
              ))}
            </ul>
          ) : (
            "Not documented on the pages we read."
          )}
        </dd>
      </div>
      <div>
        <dt className={label}>What to do instead</dt>
        <dd className="text-text [overflow-wrap:anywhere]">{card.instead}</dd>
      </div>
    </dl>
  );
}

/** The shareable page for an app that gets a card rather than a guide. */
export function AppCardView({ card }: { card: AppCard }) {
  return (
    <section aria-labelledby="card-heading">
      <Link
        href="/generate"
        className="mb-[22px] inline-flex items-center gap-1.5 text-[14px] text-text-2 hover:text-text"
      >
        <ChevronLeft size={16} aria-hidden="true" />
        Back to generator
      </Link>

      <div className="flex flex-wrap items-start justify-between gap-[18px] border-b border-border pb-6">
        <div className="min-w-0">
          <h1
            id="card-heading"
            className="mb-1.5 text-[28px] leading-[1.15] font-semibold tracking-[-.02em] [overflow-wrap:anywhere] max-sm:text-[24px]"
          >
            {card.name}
          </h1>
          <div className="flex flex-wrap items-center gap-2 text-[14px] text-text-2">
            <CategoryTag category={card.category} />
            <span className={pill}>Generated by agent</span>
            <time dateTime={card.generatedAt}>{formatGeneratedAt(card.generatedAt)}</time>
          </div>
        </div>
        <ShareButton label="Share result" />
      </div>

      <div className="mt-6 grid grid-cols-[minmax(0,1fr)_340px] items-start gap-8 max-lg:grid-cols-1">
        <div className={`${panel} p-5`}>
          <h2 className="mb-1 text-[17.5px] font-semibold tracking-[-.01em]">No setup guide for this app</h2>
          <p className="mb-5 text-[14px] text-text-2">{cardHeadline(card)}.</p>
          <CardFacts card={card} />
        </div>

        <div className={panel}>
          <div className={panelHeader}>
            <h2>Sources checked</h2>
          </div>
          <SourceList sources={card.sources} />
        </div>
      </div>
    </section>
  );
}
